#!/usr/bin/env bash
# OrbitNest Workspaces: Linux installer (also used inside WSL 2 by install-windows.ps1).
# Creates a virtualenv, installs dependencies, writes a private config file, migrates the database.
# Needs no root. Does not install Docker: it only reports whether Docker is usable.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/orbitnest"
DATA_DIR="${ORBITNEST_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/orbitnest}"
VENV="$DATA_DIR/venv"
ENV_FILE="$CONFIG_DIR/orbitnest.env"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

PY="${PYTHON:-python3}"
command -v "$PY" >/dev/null 2>&1 || die "python3 not found. Install Python 3.11 or newer (for example: sudo apt install python3 python3-venv)."
"$PY" - <<'PYEOF' || die "Python 3.11 or newer is required."
import sys
sys.exit(0 if sys.version_info >= (3, 11) else 1)
PYEOF
"$PY" -c "import venv, ensurepip" 2>/dev/null || die "the venv module is missing (Debian/Ubuntu: sudo apt install python3-venv)."

umask 077
mkdir -p "$CONFIG_DIR" "$DATA_DIR"
chmod 700 "$CONFIG_DIR" "$DATA_DIR"

if [ ! -x "$VENV/bin/python" ]; then
  say "Creating virtualenv in $VENV"
  "$PY" -m venv "$VENV"
fi
say "Installing dependencies (needs access to the Python package index)"
"$VENV/bin/python" -m pip install --quiet --upgrade pip
"$VENV/bin/python" -m pip install --quiet -r "$REPO_DIR/backend/requirements.txt"
if [ "${ORBITNEST_WITH_ARGON2:-1}" = "1" ]; then
  "$VENV/bin/python" -m pip install --quiet "argon2-cffi>=23.1" || say "note: argon2-cffi failed to install; the scrypt fallback will be used."
fi

if [ ! -f "$ENV_FILE" ]; then
  SECRET="$("$VENV/bin/python" -c 'import secrets; print(secrets.token_urlsafe(48))')"
  cat >"$ENV_FILE" <<ENVEOF
# Generated by install-linux.sh. Keep this file private (mode 600).
ORBITNEST_ENV=production
ORBITNEST_HOST=127.0.0.1
ORBITNEST_PORT=8765
ORBITNEST_DATA_DIR=$DATA_DIR
ORBITNEST_SECRET_KEY=$SECRET
# Behind a TLS reverse proxy, also set:
# ORBITNEST_PUBLIC_URL=https://nest.example.com
# ORBITNEST_TRUSTED_PROXY=true
ENVEOF
  chmod 600 "$ENV_FILE"
  say "Wrote $ENV_FILE"
else
  say "Keeping existing $ENV_FILE"
fi

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a
cd "$REPO_DIR/backend"
"$VENV/bin/python" -m app migrate

say ""
say "Platform check:"
"$VENV/bin/python" -m app capabilities | "$VENV/bin/python" -c '
import json, sys
c = json.load(sys.stdin)
print("  mode:", c.get("mode"))
for name, f in c.get("features", {}).items():
    print("  " + name + ": " + str(f.get("state")) + " - " + str(f.get("reason") or ""))
' || true

# One-word launcher: orbitnest start | stop | status | update
BIN_DIR="$HOME/.local/bin"
mkdir -p "$BIN_DIR"
ln -sf "$REPO_DIR/scripts/orbitnest" "$BIN_DIR/orbitnest"
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) say "Add $BIN_DIR to your PATH (echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.bashrc, then reopen the terminal).";; esac

cat <<NEXT

Next steps:
  1. Create the first administrator (prompts for a password):   orbitnest create-admin <username>
  2. Start the server:                                          orbitnest start
  3. Open http://127.0.0.1:8765
  Later, to get new versions from GitHub:                       orbitnest update
  Other commands: orbitnest stop | restart | status | logs
For access from other machines, put a TLS reverse proxy in front (deploy/caddy, deploy/nginx).
Never expose the plain HTTP port to the internet.
NEXT
