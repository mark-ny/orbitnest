#!/data/data/com.termux/files/usr/bin/bash
# OrbitNest Workspaces: Termux (Android, no root) installer.
#
# HONEST LIMITS: ordinary Termux cannot run Docker Engine. Workspaces here are local folders and
# local processes running as your Termux user. That is NOT an isolation boundary. Only the
# administrator can open terminals, and only templates that make sense without containers are
# offered. For real isolation, run OrbitNest on a remote Linux host and use Termux as a client.
set -eu

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DATA_DIR="${ORBITNEST_DATA_DIR:-$HOME/.orbitnest}"
VENV="$DATA_DIR/venv"
ENV_FILE="$DATA_DIR/orbitnest.env"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

[ -n "${TERMUX_VERSION:-}" ] || case "${PREFIX:-}" in *com.termux*) ;; *) die "this script is for Termux. Use scripts/install-linux.sh on Linux.";; esac

say "Installing packages with pkg (Python, build tools needed by some wheels)"
pkg update -y
pkg install -y python rust binutils make clang libffi openssl git

umask 077
mkdir -p "$DATA_DIR"
chmod 700 "$DATA_DIR"
if [ ! -x "$VENV/bin/python" ]; then
  python -m venv "$VENV"
fi
# pydantic-core is a Rust extension. On Termux there may be no prebuilt wheel, so pip compiles it,
# which can take many minutes and several hundred MB. ANDROID_API_LEVEL is needed by some builds.
export ANDROID_API_LEVEL="${ANDROID_API_LEVEL:-$(getprop ro.build.version.sdk 2>/dev/null || echo 24)}"
unset CARGO_BUILD_TARGET  # an empty value makes cargo fail with "target was empty"
"$VENV/bin/python" -m pip install --upgrade pip
"$VENV/bin/python" -m pip install -r "$REPO_DIR/backend/requirements.txt" ||
  die "dependency install failed. See docs/TERMUX.md (troubleshooting) for the pydantic-core build notes."

if [ ! -f "$ENV_FILE" ]; then
  SECRET="$("$VENV/bin/python" -c 'import secrets; print(secrets.token_urlsafe(48))')"
  cat >"$ENV_FILE" <<ENVEOF
# Generated by install-termux.sh. Keep private.
ORBITNEST_ENV=production
ORBITNEST_HOST=127.0.0.1
ORBITNEST_PORT=8765
ORBITNEST_DATA_DIR=$DATA_DIR
ORBITNEST_SECRET_KEY=$SECRET
# Plain HTTP on loopback; Secure cookies would not be sent over http://127.0.0.1 by every browser.
ORBITNEST_COOKIE_SECURE=never
ENVEOF
  chmod 600 "$ENV_FILE"
fi

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a
cd "$REPO_DIR/backend"
"$VENV/bin/python" -m app migrate
say ""
say "Capability report (what this device can honestly do):"
"$VENV/bin/python" -m app capabilities | head -40

# One-word launcher: orbitnest start | stop | status | update
BIN_DIR="${PREFIX:-$HOME/.local}/bin"
mkdir -p "$BIN_DIR"
ln -sf "$REPO_DIR/scripts/orbitnest" "$BIN_DIR/orbitnest"

cat <<NEXT

Next steps:
  1. Create the administrator:   orbitnest create-admin <username>
  2. Start the server:           orbitnest start
  3. Open http://127.0.0.1:8765 in the phone's browser.
  Later, to get new versions from GitHub:   orbitnest update
  Other commands: orbitnest stop | restart | status | logs
Run termux-wake-lock so Android is less likely to stop it. See docs/TERMUX.md.
NEXT
