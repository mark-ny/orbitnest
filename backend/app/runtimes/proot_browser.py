"""A streamed private browser for Termux, without Docker: Chromium inside a proot-distro userland.

READ THIS FIRST. THIS IS NOT A SANDBOX. proot is a userspace trick that fakes a root filesystem; the
browser runs as the same Android user as the control plane, can read whatever that user can read, and
shares the phone's network. What this adapter provides instead of isolation:

* Streaming: an X server with a VNC endpoint on a *unix socket* inside the per-session folder (mode
  0600, in a 0700 directory). No TCP port is opened for it, so other apps on the phone cannot
  connect. The control plane reads the screen through ``socat`` exactly as the container runtime
  reads it through ``docker exec``, and the viewer page is the same noVNC client.
* Tor, without a firewall: Android gives an unprivileged app no iptables, so traffic cannot be forced
  through Tor the way the container gateway does it. Instead Tor runs inside the session and Chromium
  is started with an explicit SOCKS5 proxy, with local DNS resolution disabled (so lookups happen
  over Tor) and QUIC / non-proxied WebRTC UDP switched off. If Tor is not ready the browser is never
  started, and if Tor dies the browser has no route (Chromium does not fall back to a direct
  connection when an explicit proxy fails). This is a browser *setting*, not a network guarantee: a
  compromised browser could ignore it, and other apps on the phone are not affected by it.
* Wipe on stop: the profile, Tor state, downloads and sockets all live in one session folder that is
  deleted whenever the session stops or is removed.

It uses the phone's own CPU and RAM. UNVERIFIED: written and tested only against a stand-in for
``proot-distro`` (no Termux, Android or proot in the development sandbox); the first real run on a
phone is the real test.
"""

from __future__ import annotations

import contextlib
import json
import os
import re
import shutil
import signal
import socket
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

from app.runtimes.base import RuntimeAdapter, RuntimeFailure, RuntimeSpec, RuntimeState
from app.runtimes.termux_runtime import _proc_start_ticks, _proc_state

RID_RE = re.compile(r"^phone-[a-z0-9]{10,40}-[0-9a-f]{6,16}\Z")
# What proot-distro / Termux binaries need to run. Deliberately NOT the control plane's environment,
# which holds the server's secret key.
LAUNCH_ENV_KEYS = (
    "PATH", "HOME", "PREFIX", "TMPDIR", "LANG", "TERM", "LD_PRELOAD", "LD_LIBRARY_PATH",
    "ANDROID_DATA", "ANDROID_ROOT", "ANDROID_RUNTIME_ROOT", "ANDROID_TZDATA_ROOT",
)  # fmt: skip
DISTRO = "debian"
RESOLUTION = "1280x720"
DEFAULT_PREFIX = "/data/data/com.termux/files/usr"
# Packages installed once into the Debian userland.
PACKAGES = (
    "chromium", "tigervnc-standalone-server", "tor", "novnc", "ca-certificates", "fonts-dejavu-core",
)  # fmt: skip
POLICY = {
    "WebRtcIPHandling": "disable_non_proxied_udp",
    "QuicAllowed": False,
    "MetricsReportingEnabled": False,
    "SafeBrowsingProtectionLevel": 0,
    "SyncDisabled": True,
    "BrowserSignin": 0,
    "DefaultGeolocationSetting": 2,
    "DefaultNotificationsSetting": 2,
    "SpellCheckServiceEnabled": False,
    "PasswordManagerEnabled": False,
    "BackgroundModeEnabled": False,
    "NetworkPredictionOptions": 2,
    "EnableMediaRouter": False,
}


def default_rootfs(distro: str = DISTRO) -> Path:
    prefix = os.environ.get("PREFIX", DEFAULT_PREFIX)
    return Path(prefix) / "var" / "lib" / "proot-distro" / "installed-rootfs" / distro


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def run_script(socks_port: int) -> str:
    """The shell script that runs INSIDE the userland (as proot's fake root)."""
    return f"""#!/bin/sh
# Generated by OrbitNest for one private-browser session. Everything it writes is under /session.
export HOME=/session/home TZ=UTC LANG=C.UTF-8 DISPLAY=:1 XDG_RUNTIME_DIR=/session/run
mkdir -p /session/home /session/tor /session/run /session/profile
chmod 700 /session/run
cleanup() {{ kill $(jobs -p) 2>/dev/null; }}
trap cleanup EXIT INT TERM

Xvnc :1 -geometry {RESOLUTION} -depth 16 -rfbunixpath /session/vnc.sock -rfbunixmode 0600 \\
  -SecurityTypes None -rfbport -1 -nolisten tcp -AlwaysShared >/session/xvnc.log 2>&1 &
tor --DataDirectory /session/tor --ClientOnly 1 --SocksPort 127.0.0.1:{socks_port} \\
  --Log "notice file /session/tor.log" >/session/tor.out 2>&1 &

# Fail closed: the browser does not exist until Tor has finished bootstrapping.
i=0
until grep -q "Bootstrapped 100%" /session/tor.log 2>/dev/null; do
  i=$((i + 1))
  if [ "$i" -gt 240 ]; then echo "Tor did not finish connecting in time." >/session/error.txt; exit 1; fi
  sleep 1
done

chromium --no-sandbox --test-type --no-first-run --no-default-browser-check \\
  --disable-gpu --disable-dev-shm-usage --disable-sync --disable-extensions \\
  --disable-background-networking --disable-component-update --disable-quic \\
  --lang=en-US --accept-lang=en-US,en \\
  --force-webrtc-ip-handling-policy=disable_non_proxied_udp \\
  --proxy-server="socks5://127.0.0.1:{socks_port}" \\
  --host-resolver-rules="MAP * ~NOTFOUND , EXCLUDE 127.0.0.1" \\
  --user-data-dir=/session/profile --window-position=0,0 --window-size={RESOLUTION.replace("x", ",")} \\
  about:blank
"""


def setup_commands(proot_bin: str = "proot-distro", rootfs: Path | None = None) -> list[list[str]]:
    """The one-time installation, as argv lists (the CLI runs and prints them)."""
    steps: list[list[str]] = []
    if not (rootfs or default_rootfs()).is_dir():
        steps.append([proot_bin, "install", DISTRO])
    policy = json.dumps(POLICY, separators=(",", ":"))
    inside = (
        "apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "
        + " ".join(PACKAGES)
        + " && mkdir -p /etc/chromium/policies/managed"
        + f" && printf '%s' '{policy}' > /etc/chromium/policies/managed/orbitnest-privacy.json"
    )
    steps.append([proot_bin, "login", DISTRO, "--", "sh", "-c", inside])
    return steps


@dataclass
class ProotBrowserRuntime(RuntimeAdapter):
    state_dir: Path
    proot_bin: str = "proot-distro"
    rootfs: Path | None = None
    startup_seconds: float = 60.0
    name: str = "proot-browser"
    isolation: str = "none"
    streams: bool = True
    _children: dict[str, subprocess.Popen[bytes]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if sys.platform.startswith("win"):
            raise RuntimeFailure("the phone browser runtime is POSIX only")
        self.state_dir = Path(self.state_dir)
        self.state_dir.mkdir(parents=True, exist_ok=True)
        with contextlib.suppress(OSError):
            self.state_dir.chmod(0o700)
        if self.rootfs is None:
            self.rootfs = default_rootfs()

    # -- readiness ---------------------------------------------------------------------------
    def not_ready(self) -> tuple[str, str] | None:
        """(why, how to fix) unless the Debian userland has everything the session needs."""
        assert self.rootfs is not None
        fix = "Run in Termux: orbitnest setup-phone-browser"
        if shutil.which(self.proot_bin) is None and not Path(self.proot_bin).is_file():
            return ("proot-distro is not installed.", "Run in Termux: pkg install proot-distro socat")
        needed = ("usr/bin/chromium", "usr/bin/Xvnc", "usr/bin/tor", "usr/share/novnc/core/rfb.js")
        missing = [n for n in needed if not (self.rootfs / n).exists()]
        if missing:
            return (f"The phone browser's Debian userland is not set up yet (missing {missing[0]}).", fix)
        return None

    # -- files -------------------------------------------------------------------------------
    def _rid(self, rid: str) -> str:
        if not RID_RE.match(rid):
            raise RuntimeFailure("invalid resource id")
        return rid

    def _state_path(self, rid: str) -> Path:
        return self.state_dir / f"{self._rid(rid)}.json"

    def _session(self, rid: str) -> Path:
        return self.state_dir / f"{self._rid(rid)}.session"

    def _load(self, rid: str) -> dict | None:
        try:
            return json.loads(self._state_path(rid).read_text())
        except (OSError, json.JSONDecodeError):
            return None

    def _save(self, rid: str, data: dict) -> None:
        tmp = self._state_path(rid).with_suffix(".tmp")
        tmp.write_text(json.dumps(data))
        os.replace(tmp, self._state_path(rid))

    def _wipe(self, rid: str) -> None:
        """Erase the whole session: profile, history, cookies, downloads, Tor state, sockets."""
        shutil.rmtree(self._session(rid), ignore_errors=True)

    def _env(self) -> dict[str, str]:
        return {k: os.environ[k] for k in LAUNCH_ENV_KEYS if k in os.environ}

    # -- liveness ----------------------------------------------------------------------------
    def _alive(self, rid: str, data: dict) -> bool:
        pid = data.get("pid")
        if not pid:
            return False
        child = self._children.get(rid)
        if child is not None:
            return child.poll() is None
        if _proc_state(pid) == "Z":
            return False
        ticks = data.get("start_ticks")
        if ticks is not None:
            return _proc_start_ticks(pid) == ticks
        try:
            os.kill(pid, 0)
        except (ProcessLookupError, PermissionError):
            return False
        return True

    # -- adapter API -------------------------------------------------------------------------
    def create(self, spec: RuntimeSpec) -> str:
        spec.validate()
        rid = f"phone-{spec.workspace_id.lower()}-{int(time.time() * 1000):x}"
        self._save(
            rid,
            {"workspace_id": spec.workspace_id, "running": False, "started_once": False, "pid": None,
             "start_ticks": None, "labels": dict(spec.labels)},
        )  # fmt: skip
        return rid

    def start(self, resource_id: str) -> None:
        data = self._load(resource_id)
        if data is None:
            raise RuntimeFailure("resource not found", operation="start")
        if data["running"] and self._alive(resource_id, data):
            return
        problem = self.not_ready()
        if problem is not None:
            raise RuntimeFailure(f"{problem[0]} {problem[1]}", operation="start")
        session = self._session(resource_id)
        self._wipe(resource_id)  # never reuse anything from a previous session
        session.mkdir(parents=True)
        session.chmod(0o700)
        (session / "run.sh").write_text(run_script(free_port()))
        (session / "run.sh").chmod(0o700)
        argv = [
            self.proot_bin, "login", DISTRO, "--isolated", "--bind", f"{session}:/session",
            "--", "/bin/sh", "/session/run.sh",
        ]  # fmt: skip
        log_path = self.state_dir / f"{resource_id}.log"
        try:
            with open(log_path, "ab") as log:
                child = subprocess.Popen(  # noqa: S603 - fixed argv, no shell, minimal environment
                    argv,
                    env=self._env(),
                    cwd=str(session),
                    stdin=subprocess.DEVNULL,
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    start_new_session=True,
                    close_fds=True,
                )
        except OSError as exc:
            self._wipe(resource_id)
            why = exc.strerror or "os error"
            raise RuntimeFailure(f"could not start proot-distro: {why}", operation="start") from None
        self._children[resource_id] = child
        data.update(running=True, started_once=True, pid=child.pid, start_ticks=_proc_start_ticks(child.pid))
        self._save(resource_id, data)
        # The viewer needs the screen socket; the browser itself appears after Tor has connected.
        sock = session / "vnc.sock"
        deadline = time.monotonic() + self.startup_seconds
        while time.monotonic() < deadline:
            if child.poll() is not None:
                break
            if sock.exists():
                return
            time.sleep(0.2)
        reason = self._failure_reason(resource_id)
        with contextlib.suppress(RuntimeFailure):
            self.stop(resource_id, 2)
        raise RuntimeFailure(reason, operation="start")

    def _failure_reason(self, rid: str) -> str:
        session = self._session(rid)
        for name in ("error.txt", "xvnc.log"):
            with contextlib.suppress(OSError):
                text = (session / name).read_text(errors="replace").strip().splitlines()
                if text:
                    return f"The private browser did not start: {text[-1][:160]}"
        return "The private browser did not start (proot-distro exited). See the server log."

    def stop(self, resource_id: str, grace_seconds: int) -> None:
        data = self._load(resource_id)
        if data is None:
            return
        pid = data.get("pid")
        if pid and self._alive(resource_id, data):
            self._signal_group(pid, signal.SIGTERM)
            deadline = time.monotonic() + max(0.1, grace_seconds)
            while time.monotonic() < deadline and self._alive(resource_id, data):
                time.sleep(0.05)
            if self._alive(resource_id, data):
                self._signal_group(pid, signal.SIGKILL)
                end = time.monotonic() + 5
                while time.monotonic() < end and self._alive(resource_id, data):
                    time.sleep(0.05)
                if self._alive(resource_id, data):
                    raise RuntimeFailure("the private browser did not stop", operation="stop")
        child = self._children.pop(resource_id, None)
        if child is not None:
            with contextlib.suppress(subprocess.TimeoutExpired):
                child.wait(timeout=1)
        self._wipe(resource_id)  # "after finishing everything is wiped clean"
        data.update(running=False, pid=None, start_ticks=None)
        self._save(resource_id, data)

    @staticmethod
    def _signal_group(pid: int, sig: signal.Signals) -> None:
        with contextlib.suppress(ProcessLookupError, PermissionError):
            os.killpg(os.getpgid(pid), sig)

    def remove(self, resource_id: str) -> None:
        if self._load(resource_id) is not None:
            self.stop(resource_id, 2)
        self._wipe(resource_id)
        for suffix in (".json", ".log", ".tmp"):
            with contextlib.suppress(OSError):
                (self.state_dir / f"{self._rid(resource_id)}{suffix}").unlink()

    def inspect(self, resource_id: str) -> RuntimeState:
        data = self._load(resource_id)
        if data is None:
            return RuntimeState("missing")
        if not data["running"]:
            if data.get("started_once"):
                return RuntimeState("exited", exit_code=0)
            return RuntimeState("created")
        if self._alive(resource_id, data):
            return RuntimeState("running")
        child = self._children.get(resource_id)
        return RuntimeState(
            "exited", exit_code=child.returncode if child else None, detail=self._failure_reason(resource_id)
        )

    # -- streaming ---------------------------------------------------------------------------
    def stream_bridge_argv(self, resource_id: str, port: int) -> tuple[list[str], dict[str, str]]:
        sock = self._session(resource_id) / "vnc.sock"
        if not sock.exists():
            raise RuntimeFailure("The private browser's screen is not ready yet.", operation="stream")
        return (["socat", "-", f"UNIX-CONNECT:{sock}"], {"PATH": os.environ.get("PATH", "")})

    def asset_argv(self, resource_id: str, path: str) -> tuple[list[str], dict[str, str]]:
        assert self.rootfs is not None
        root = (self.rootfs / "usr" / "share" / "novnc").resolve()
        target = (root / path).resolve()
        if not target.is_relative_to(root) or not target.is_file():
            raise RuntimeFailure("viewer file not found", operation="stream")
        return (["cat", str(target)], {"PATH": os.environ.get("PATH", "")})

    def list_managed(self) -> dict[str, dict[str, str]]:
        found = {}
        for path in self.state_dir.glob("phone-*.json"):
            if RID_RE.match(path.stem):
                data = self._load(path.stem)
                if data is not None:
                    found[path.stem] = dict(data.get("labels", {}))
        return found
